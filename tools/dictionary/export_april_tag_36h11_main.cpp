// Exports OpenCV's DICT_APRILTAG_36h11 into a C++ header with a constexpr code table.
// - Output: april_tag_36h11_codes[id][rotation], 36 bits per code in a std::uint64_t.
// - All 4 rotations are taken from OpenCV's own byte list, so the rotation numbering is
//   exactly the one cv::aruco::Dictionary::identify returns.
// - Every exported code is checked by converting it back with OpenCV before writing.
// Usage: ppmt_fiducial_export_april_tag_36h11 <output_header_path>
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <string>

#include <opencv2/aruco.hpp>
#include <opencv2/core.hpp>

namespace
{

constexpr int marker_size = 6;   // 6x6 data bits
constexpr int code_bit_count = marker_size * marker_size;
constexpr int byte_count = 5;    // OpenCV packs 36 bits into 5 bytes
constexpr int rotation_count = 4;

// OpenCV byte layout (checked on 4.5.4 by probing single bits):
// - The 4 rotations are stored one after another: rotation r = raw bytes [r*5, r*5 + 5).
//   Not one rotation per Vec4b channel, although the Mat is CV_8UC4.
// - Within a rotation: bytes 0..3 hold bits 0..31 most significant bit first; byte 4 holds
//   the last 4 bits in its low nibble.
// Result: bit 35 = cell (0, 0), row-major, 1 = white.
const std::uint8_t * rotationBytes(const cv::Mat & byte_list_row, int rotation)
{
  return byte_list_row.ptr<std::uint8_t>() + rotation * byte_count;
}

std::uint64_t codeFromBytes(const cv::Mat & byte_list_row, int rotation)
{
  const std::uint8_t * bytes = rotationBytes(byte_list_row, rotation);
  std::uint64_t code = 0;
  for (int byte_index = 0; byte_index < byte_count - 1; ++byte_index) {
    code = (code << 8) | bytes[byte_index];
  }
  const int last_byte_bits = code_bit_count - 8 * (byte_count - 1);  // 4
  return (code << last_byte_bits) | (bytes[byte_count - 1] & ((1U << last_byte_bits) - 1U));
}

cv::Mat bitsFromCode(std::uint64_t code)
{
  cv::Mat bits(marker_size, marker_size, CV_8UC1);
  for (int cell = 0; cell < code_bit_count; ++cell) {
    const int bit_index = code_bit_count - 1 - cell;
    bits.at<std::uint8_t>(cell / marker_size, cell % marker_size) = (code >> bit_index) & 1U;
  }
  return bits;
}

// The code of `rotation`, turned back into bits by OpenCV, must give rotation-0 bytes equal
// to OpenCV's stored bytes of `rotation`: proves the byte layout for every rotation.
bool codeMatchesOpenCv(std::uint64_t code, const cv::Mat & byte_list_row, int rotation)
{
  const cv::Mat round_trip = cv::aruco::Dictionary::getByteListFromBits(bitsFromCode(code));
  const std::uint8_t * expected = rotationBytes(byte_list_row, rotation);
  const std::uint8_t * actual = rotationBytes(round_trip, 0);
  return std::equal(actual, actual + byte_count, expected);
}

}  // namespace

int main(int argc, char ** argv)
{
  if (argc != 2) {
    std::fprintf(stderr, "usage: %s <output_header_path>\n", argv[0]);
    return 1;
  }

  const cv::Ptr<cv::aruco::Dictionary> dictionary =
    cv::aruco::getPredefinedDictionary(cv::aruco::DICT_APRILTAG_36h11);
  if (dictionary->markerSize != marker_size || dictionary->bytesList.cols != byte_count ||
      dictionary->bytesList.channels() != rotation_count) {
    std::fprintf(stderr, "unexpected OpenCV dictionary layout\n");
    return 1;
  }
  const int code_count = dictionary->bytesList.rows;

  std::ofstream out(argv[1]);
  out << "#pragma once\n"
      << "// GENERATED by ppmt_fiducial_export_april_tag_36h11 from OpenCV " << CV_VERSION
      << " DICT_APRILTAG_36h11. Do not edit.\n"
      << "// - april_tag_36h11_codes[id][rotation]: 36 data bits, row-major from the top-left\n"
      << "//   cell; bit 35 = cell (0, 0); 1 = white.\n"
      << "// - rotation numbering = cv::aruco::Dictionary::identify.\n\n"
      << "#include <array>\n#include <cstdint>\n\n"
      << "namespace ppmt::fiducial\n{\n\n"
      << "inline constexpr int april_tag_36h11_code_count = " << code_count << ";\n\n"
      << "inline constexpr std::array<std::array<std::uint64_t, 4>, april_tag_36h11_code_count>\n"
      << "  april_tag_36h11_codes = {{\n";

  for (int id = 0; id < code_count; ++id) {
    const cv::Mat byte_list_row = dictionary->bytesList.row(id);
    out << "    {{";
    for (int rotation = 0; rotation < rotation_count; ++rotation) {
      const std::uint64_t code = codeFromBytes(byte_list_row, rotation);
      if (!codeMatchesOpenCv(code, byte_list_row, rotation)) {
        std::fprintf(stderr, "id %d rotation %d: code does not round-trip through OpenCV\n",
                     id, rotation);
        return 1;
      }
      char hex[32];
      std::snprintf(hex, sizeof(hex), "0x%09llXULL", static_cast<unsigned long long>(code));
      out << hex << (rotation + 1 < rotation_count ? ", " : "");
    }
    out << "}},  // id " << id << "\n";
  }
  out << "}};\n\n}  // namespace ppmt::fiducial\n";

  std::printf("wrote %d codes x %d rotations to %s\n", code_count, rotation_count, argv[1]);
  return 0;
}
